// PJ4: storage type of a field, from its FMT format character. Values are decoded to double
// exactly as in PJ3; a field that no multiplier touched is written back with its native type.
PJ::PrimitiveType primitive_type_for(char type_code)
{
  switch (type_code)
  {
    case 'b': return PJ::PrimitiveType::kInt8;
    case 'B': return PJ::PrimitiveType::kUint8;
    case 'h': return PJ::PrimitiveType::kInt16;
    case 'H': return PJ::PrimitiveType::kUint16;
    case 'i': return PJ::PrimitiveType::kInt32;
    case 'I': return PJ::PrimitiveType::kUint32;
    case 'f': return PJ::PrimitiveType::kFloat32;
    case 'd': return PJ::PrimitiveType::kFloat64;
    case 'c': return PJ::PrimitiveType::kInt16;
    case 'C': return PJ::PrimitiveType::kUint16;
    case 'e': return PJ::PrimitiveType::kInt32;
    case 'E': return PJ::PrimitiveType::kUint32;
    case 'L': return PJ::PrimitiveType::kInt32;
    case 'M': return PJ::PrimitiveType::kUint8;
    case 'q': return PJ::PrimitiveType::kInt64;
    case 'Q': return PJ::PrimitiveType::kUint64;
    default:
      // 'a', 'n', 'N', 'Z' (not decoded, see handle_message_received) and unknown types
      return PJ::PrimitiveType::kFloat64;
  }
}

PJ::sdk::ValueRef value_ref_for(PJ::PrimitiveType type, double value)
{
  switch (type)
  {
    case PJ::PrimitiveType::kInt8: return static_cast<int8_t>(value);
    case PJ::PrimitiveType::kUint8: return static_cast<uint8_t>(value);
    case PJ::PrimitiveType::kInt16: return static_cast<int16_t>(value);
    case PJ::PrimitiveType::kUint16: return static_cast<uint16_t>(value);
    case PJ::PrimitiveType::kInt32: return static_cast<int32_t>(value);
    case PJ::PrimitiveType::kUint32: return static_cast<uint32_t>(value);
    case PJ::PrimitiveType::kInt64: return static_cast<int64_t>(value);
    case PJ::PrimitiveType::kUint64: return static_cast<uint64_t>(value);
    case PJ::PrimitiveType::kFloat32: return static_cast<float>(value);
    default: return value;
  }
}

// PJ4: PJ3 timestamps are seconds as double; the datastore wants absolute nanoseconds.
PJ::Timestamp to_timestamp(double seconds)
{
  return PJ::Timestamp{static_cast<int64_t>(std::llround(seconds * 1e9))};
}

// Vehicle pose for the 3D view. ArduPilot logs attitude as body FRD relative to NED (Euler ZYX,
// degrees); the 3D view uses ROS conventions (world ENU, body FLU, REP-103). With T the NED->ENU
// swap and S the FLU->FRD flip, R_enu_flu = T * Rz(yaw) Ry(pitch) Rx(roll) * S.
PJ::sdk::Quaternion enu_flu_quaternion(double roll_deg, double pitch_deg, double yaw_deg)
{
  constexpr double kDegToRad = 3.14159265358979323846 / 180.0;
  const double cr = std::cos(roll_deg * kDegToRad), sr = std::sin(roll_deg * kDegToRad);
  const double cp = std::cos(pitch_deg * kDegToRad), sp = std::sin(pitch_deg * kDegToRad);
  const double cy = std::cos(yaw_deg * kDegToRad), sy = std::sin(yaw_deg * kDegToRad);
  // Body FRD -> NED.
  const double ned[3][3] = {
      {cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr},
      {sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr},
      {-sp, cp * sr, cp * cr},
  };
  // T swaps rows 0/1 and negates row 2; S negates columns 1 and 2.
  double m[3][3];
  const int row_of[3] = {1, 0, 2};
  const double row_sign[3] = {1.0, 1.0, -1.0};
  const double col_sign[3] = {1.0, -1.0, -1.0};
  for (int r = 0; r < 3; ++r)
  {
    for (int c = 0; c < 3; ++c)
    {
      m[r][c] = row_sign[r] * ned[row_of[r]][c] * col_sign[c];
    }
  }
  // Rotation matrix -> unit quaternion (Shepperd's method).
  PJ::sdk::Quaternion q;
  const double trace = m[0][0] + m[1][1] + m[2][2];
  if (trace > 0.0)
  {
    const double s = std::sqrt(trace + 1.0) * 2.0;
    q.w = 0.25 * s;
    q.x = (m[2][1] - m[1][2]) / s;
    q.y = (m[0][2] - m[2][0]) / s;
    q.z = (m[1][0] - m[0][1]) / s;
  }
  else if (m[0][0] > m[1][1] && m[0][0] > m[2][2])
  {
    const double s = std::sqrt(1.0 + m[0][0] - m[1][1] - m[2][2]) * 2.0;
    q.w = (m[2][1] - m[1][2]) / s;
    q.x = 0.25 * s;
    q.y = (m[0][1] + m[1][0]) / s;
    q.z = (m[0][2] + m[2][0]) / s;
  }
  else if (m[1][1] > m[2][2])
  {
    const double s = std::sqrt(1.0 + m[1][1] - m[0][0] - m[2][2]) * 2.0;
    q.w = (m[0][2] - m[2][0]) / s;
    q.x = (m[0][1] + m[1][0]) / s;
    q.y = 0.25 * s;
    q.z = (m[1][2] + m[2][1]) / s;
  }
  else
  {
    const double s = std::sqrt(1.0 + m[2][2] - m[0][0] - m[1][1]) * 2.0;
    q.w = (m[1][0] - m[0][1]) / s;
    q.x = (m[0][2] + m[2][0]) / s;
    q.y = (m[1][2] + m[2][1]) / s;
    q.z = 0.25 * s;
  }
  return q;
}

class APBinSource : public PJ::FileSourceBase
{
public:
  uint64_t extraCapabilities() const override
  {
    return PJ::kCapabilityDirectIngest;
  }

  std::string saveConfig() const override
  {
    return nlohmann::json{{"filepath", filepath_}}.dump();
  }

  PJ::Status loadConfig(std::string_view config_json) override
  {
    auto cfg = nlohmann::json::parse(config_json, nullptr, false);
    if (cfg.is_discarded())
    {
      return PJ::unexpected(std::string("invalid config JSON"));
    }
    filepath_ = cfg.value("filepath", std::string{});
    return PJ::okStatus();
  }

  PJ::Status importData() override
  {
    // PJ4: nothing may throw across the plugin ABI.
    try
    {
      return readDataFromFile();
    }
    catch (const std::exception& e)
    {
      return PJ::unexpected(std::string("ArduPilot Bin: ") + e.what());
    }
  }

private:
  std::string filepath_;

  // message_data holds the data of a message for each timestamp
  //  - std::string:  field name (label)
  //  - std::vector:  field data (fields)
  typedef std::vector<std::pair<std::string, std::vector<double>>> message_data;

  // messages_map is a nested map which contains all messages
  //  - key1:   message name
  //  - key2:   instance identifier (numeric value stringified, or full decoded
  //            string for N/n/Z-typed instance fields like SCR.Name)
  //  - value:  message_data
  std::map<std::string, std::map<std::string, message_data>> messages_map;


  // multipliers and units from MULT and UNIT messages
  std::map<char, double> multipliers;
  std::map<char, std::string> units;


  // format (FMT) and format unit (FMTU) handling variables
  static constexpr uint16_t MAX_FORMATS = 256;
  struct log_Format formats[MAX_FORMATS] = {};            // FMT
  struct log_Format_Units format_units[MAX_FORMATS] = {}; // FMTU

  bool has_fmt[MAX_FORMATS] = {false};    // indicator, if FMT for a given message id exists
  bool has_fmtu[MAX_FORMATS] = {false};   // indicator, if FMTU for a given message id exists


  // instance handling variables
  bool has_instance[MAX_FORMATS] = {false};     // indicator, if a message contains intances
  int instance_idx[MAX_FORMATS] = {-1};         // index of field, which contains the instance number
  uint32_t instance_offset[MAX_FORMATS] = {0};  // byte-offset of field, which containts the instance number


  // message name <-> message id mapping
  std::string msg_id2name[MAX_FORMATS] = {};
  std::map<std::string, uint8_t> msg_name2id;


  // field name <-> field idx mapping
  std::map<std::string, std::map<std::string, uint8_t>> field_name2idx;

  // log messages (MSG messages)
  std::vector<APBinMessage> log_messages;

  // parameters (PARM messages) - using map to keep only the latest value per parameter
  std::map<std::string, float> log_parameters;

  // parameter default values (PARM "Default" field, newer firmware only)
  std::map<std::string, float> log_parameter_defaults;

  // all PARM entries with timestamps (for time-series plotting)
  struct ParmEntry { double timestamp; std::string name; float value; };
  std::vector<ParmEntry> parm_entries;

  // PJ4: which fields apply_multipliers() scaled (message name -> field idx). Those are
  // written as float64; every other field keeps the native type of its FMT format char.
  std::map<std::string, std::vector<bool>> scaled_fields;

  // PJ4: offset added by apply_timesync() (0 if skipped), so the _MSG topic can be time-synced.
  double time_offset_s = 0.0;

  PJ::Status readDataFromFile();
  PJ::Status publish();

  // PJ4: vehicle pose (world -> vehicle) from the EKF, as a transform topic for the 3D view.
  PJ::Status publish_vehicle_transforms();

  // fill the message_data for a message according to the message format
  void handle_message_received(const struct log_Format& fmt, const uint8_t* msg);

  // create message_data for a message
  message_data create_message_data(const struct log_Format& fmt);

  // get the byte offset of a field in a message
  uint32_t get_field_byte_offset(const uint8_t& msg_id, const uint8_t& field_idx);
  uint32_t get_field_byte_offset(const uint8_t& msg_id, const std::string& field_name);

  // get the instance identifier from a message, decoded according to the
  // FMT type of the field flagged with '#' in FMTU.units
  std::string get_instance(const struct log_Format& fmt, const uint8_t* msg);

  // get unit string for a field
  std::string get_unit(const std::string& msg_name, const std::string& field_name);

  // apply multipliers from FMTU and MULT messages to the messages_map
  void apply_multipliers(void);

  // apply time synchronization to the messages_map
  void apply_timesync(void);
};


PJ::Status APBinSource::readDataFromFile()
{
  // Clear all persistent state from previous file loads to prevent crashes
  // when loading multiple files in the same session
  messages_map.clear();
  multipliers.clear();
  units.clear();
  msg_name2id.clear();
  field_name2idx.clear();
  log_messages.clear();
  log_parameters.clear();
  log_parameter_defaults.clear();
  parm_entries.clear();
  scaled_fields.clear();
  time_offset_s = 0.0;

  for (uint16_t i = 0; i < MAX_FORMATS; i++)
  {
    has_fmt[i] = false;
    has_fmtu[i] = false;
    has_instance[i] = false;
    instance_idx[i] = -1;
    instance_offset[i] = 0;
    msg_id2name[i].clear();
    formats[i] = {};
    format_units[i] = {};
  }

  if (filepath_.empty())
  {
    return PJ::unexpected(std::string("no filepath configured"));
  }

  // PJ3: QFile::readAll(); returned false (silently) if the file could not be opened.
  std::ifstream file(filepath_, std::ios::binary);
  if (!file.is_open())
  {
    return PJ::unexpected(std::string("cannot open file: ") + filepath_);
  }

  const std::vector<uint8_t> file_array((std::istreambuf_iterator<char>(file)), std::istreambuf_iterator<char>());
  const int32_t file_size = static_cast<int32_t>(file_array.size());

  const uint8_t* buf = file_array.data();
  const uint32_t len = static_cast<uint32_t>(file_array.size());
  uint32_t total_bytes_used = 0;

  // Progress box for large file
  // PJ4: host progress bar instead of QProgressDialog (FileSourceBase finishes it after importData()).
  (void)runtimeHost().progressStart("Loading ArduPilot logfile... please wait", 100, true);

  int progress{ 0 };
  int progress_update{ 0 };

  uint32_t bytes_skipped{ 0 };
  uint32_t msgs_skipped{ 0 };
  uint32_t msgs_read{ 0 };

  const auto timer_start = std::chrono::steady_clock::now();

  #ifdef DEBUG_RUNTIME
    std::chrono::duration<double, std::milli> fmt_ms{ 0 };
    std::chrono::duration<double, std::milli> fmtu_ms{ 0 };
    std::chrono::duration<double, std::milli> mult_ms{ 0 };
    std::chrono::duration<double, std::milli> unit_ms{ 0 };
    std::chrono::duration<double, std::milli> other_ms{ 0 };
    std::chrono::duration<double, std::milli> process_units_ms{ 0 };
    std::chrono::duration<double, std::milli> apply_mult_ms{ 0 };
    std::chrono::duration<double, std::milli> apply_tsync_ms{ 0 };
    std::chrono::duration<double, std::milli> publish_ms{ 0 };
  #endif

  // ArduPilot logs emit FMTU after the first few data messages of each type,
  // so without deferral handle_message_received would see has_instance=false
  // for those early messages and bucket them under an empty instance key —
  // producing a phantom "#" series next to the real "#0"/"#1"/... at publish
  // time. Pre-FMTU messages are stashed (as pointers into the in-memory file
  // buffer) and replayed once their FMTU arrives.
  std::array<std::vector<const uint8_t*>, MAX_FORMATS> deferred_messages;

  while (true)
  {
    // update the progression dialog box
    progress_update = static_cast<int>((static_cast<double>(total_bytes_used) / static_cast<double>(file_size)) * 100.0);
    if ( (progress_update - 4) > progress )
    {
      progress = progress_update;
      // PJ3: wasCanceled() -> return false, discarding everything. Same here: fail the import.
      if (!runtimeHost().progressUpdate(static_cast<uint64_t>(progress)) || runtimeHost().isStopRequested())
      {
        return PJ::unexpected(std::string("loading cancelled"));
      }
    }

    // check if end of file is reached
    if (len - total_bytes_used < LOG_PACKET_HEADER_LEN)
    {
      (void)runtimeHost().progressUpdate(100);
      bytes_skipped += len - total_bytes_used;
      break;
    }

    // detect message start sequence (header)
    // skip through input until we find a valid header:
    if (buf[total_bytes_used] != HEAD_BYTE1 || buf[total_bytes_used + 1] != HEAD_BYTE2)
    {
      total_bytes_used += 1;
      bytes_skipped += 1;
      continue;
    }

    // get message-id from header
    const uint8_t type = buf[total_bytes_used + 2];


    // -------------------- handle FMT-message -------------------- //
    if (type == LOG_FORMAT_MSG)
    {
      #ifdef DEBUG_RUNTIME
        auto fmt_start = std::chrono::high_resolution_clock::now();
      #endif

      // check if we don't reach the end
      if ((uint32_t)(len - total_bytes_used) < sizeof(struct log_Format))
      {
        bytes_skipped += len - total_bytes_used;
        break;
      }

      // extract the message-id for which the FMT-message is defined and store FMT
      const uint8_t msg_id = ((struct log_Format*)(&(buf[total_bytes_used])))->type;
      has_fmt[msg_id] = true;
      struct log_Format& fmt = formats[msg_id];
      memcpy(&fmt, &buf[total_bytes_used], sizeof(struct log_Format));
      for (char i : fmt.name)
      {
        if (!isprint(i) && i != '\0')
        {
          // double check that this is a message
          // name is assumed to be printable ascii; it
          // looked like a format message, but wasn't.
          // (PORTING.md #6: this `continue` only continues the inner loop; translated as-is.)
          total_bytes_used++;
          bytes_skipped++;
          continue;
        }
      }

      // store message name <-> message id mapping
      uint8_t name_length = 0;
      for (char i : fmt.name)
      {
        if (i != '\0')
        {
          name_length++;
        }
      }
      std::string msg_name(fmt.name, name_length);
      msg_id2name[msg_id] = msg_name;
      msg_name2id[msg_name] = msg_id;

      // store field name (label) <-> field idx mapping
      uint8_t label_length = 0;
      for (char i : fmt.labels)
      {
        if (i != '\0')
        {
          label_length++;
        }
      }
      std::string labels(fmt.labels, label_length);
      std::vector<std::string> labels_vec{};

      // split labels at delimiter ","
      size_t pos = 0;
      std::string label;
      while ( (pos = labels.find(",")) != std::string::npos )
      {
        label = labels.substr(0,pos);
        labels_vec.push_back(label);
        labels.erase(0, pos + 1);
      }
      labels_vec.push_back(labels);

      // go through labels
      for (size_t idx = 0; idx < labels_vec.size(); idx++)
      {
        const std::string& label = labels_vec[idx];
        field_name2idx[msg_name][label] = static_cast<uint8_t>(idx);
      }

      total_bytes_used += sizeof(struct log_Format);
      msgs_read++;

      #ifdef DEBUG_RUNTIME
        auto fmt_end = std::chrono::high_resolution_clock::now();
        fmt_ms += (fmt_end - fmt_start);
      #endif

      continue;
    }

    // get the full log format from the message type
    const struct log_Format& fmt = formats[type];

    // checks:
    //  - if length of message is zero, continue
    if ( fmt.length == 0 )
    {
      total_bytes_used += 1;
      bytes_skipped += 1;
      continue;
    }
    //  - if we reached the end of the log, just end
    if (len - total_bytes_used < fmt.length)
    {
      (void)runtimeHost().progressUpdate(100);
      bytes_skipped += len - total_bytes_used;
      break;
    }


    // -------------------- handle FMTU-message -------------------- //
    if ( memcmp(fmt.name, "FMTU", 4) == 0 )
    {
      #ifdef DEBUG_RUNTIME
        auto fmtu_start = std::chrono::high_resolution_clock::now();
      #endif

      // extract the message-id for which the FMTU-message is defined and store FMTU
      const uint8_t msg_id = ((struct log_Format_Units*)(&(buf[total_bytes_used])))->format_type;
      has_fmtu[msg_id] = true;
      struct log_Format_Units& fmtu = format_units[msg_id];
      memcpy(&fmtu, &buf[total_bytes_used], sizeof(struct log_Format_Units));


      // handle instances
      //  - check if units contain "#" (see also: logformat.h)
      if ( !has_instance[msg_id] )
      {
        uint8_t units_length = 0;
        for (char i : fmtu.units)
        {
          if (i != '\0')
          {
            units_length++;
          }
        }
        std::string units(fmtu.units, units_length);

        size_t pos = units.find("#");
        if ( pos != std::string::npos )
        {
          has_instance[msg_id] = true;
          instance_idx[msg_id] = static_cast<int>(pos);
          instance_offset[msg_id] = get_field_byte_offset(msg_id, static_cast<uint8_t>(pos));
        }
      }

      // Replay any data messages that were stashed before this FMTU arrived,
      // now that has_instance is correctly set for this msg_id.
      auto& deferred = deferred_messages[msg_id];
      if ( !deferred.empty() )
      {
        const struct log_Format& fmt_for_id = formats[msg_id];
        for (const uint8_t* msg_ptr : deferred)
        {
          handle_message_received(fmt_for_id, msg_ptr);
        }
        deferred.clear();
      }

      total_bytes_used += fmt.length;
      msgs_read++;

      #ifdef DEBUG_RUNTIME
        auto fmtu_end = std::chrono::high_resolution_clock::now();
        fmtu_ms += (fmtu_end - fmtu_start);
      #endif

      continue;
    }


    // -------------------- handle MULT-message -------------------- //
    if ( memcmp(fmt.name, "MULT", 4) == 0 )
    {
      #ifdef DEBUG_RUNTIME
        auto mult_start = std::chrono::high_resolution_clock::now();
      #endif

      uint32_t id_offset = get_field_byte_offset(type, "Id");
      uint32_t mult_offset = get_field_byte_offset(type, "Mult");

      // todo: data type is hardcoded here, change that?!
      const unsigned char multiplier_char = *reinterpret_cast<const uint8_t*>(buf + total_bytes_used + id_offset);
      double multiplier;
      memcpy(&multiplier, buf + total_bytes_used + mult_offset, sizeof(multiplier));

      multipliers[multiplier_char] = multiplier;

      total_bytes_used += fmt.length;
      msgs_read++;

      #ifdef DEBUG_RUNTIME
        auto mult_end = std::chrono::high_resolution_clock::now();
        mult_ms += (mult_end - mult_start);
      #endif

      continue;
    }


    // -------------------- handle UNIT-message -------------------- //
    if ( memcmp(fmt.name, "UNIT", 4) == 0 )
    {
      #ifdef DEBUG_RUNTIME
        auto unit_start = std::chrono::high_resolution_clock::now();
      #endif

      uint32_t id_offset = get_field_byte_offset(type, "Id");
      uint32_t label_offset = get_field_byte_offset(type, "Label");

      // todo: data type is hardcoded here, change that?!
      const unsigned char unit_char = *reinterpret_cast<const uint8_t*>(buf + total_bytes_used + id_offset);
      const char* unit = reinterpret_cast<const char*>(buf + total_bytes_used + label_offset);

      units[unit_char] = std::string(unit);

      total_bytes_used += fmt.length;
      msgs_read++;

      #ifdef DEBUG_RUNTIME
        auto unit_end = std::chrono::high_resolution_clock::now();
        unit_ms += (unit_end - unit_start);
      #endif

      continue;
    }


    // -------------------- handle any other message -------------------- //

    // discard some messages that should not be used:
    //  - ISBD, ISBH, MSG, PARM,

    if ( memcmp(fmt.name, "ISBD", 4) == 0 )
    {
      total_bytes_used += fmt.length;
      msgs_skipped++;
      continue;
    }
    if ( memcmp(fmt.name, "ISBH", 4) == 0 )
    {
      total_bytes_used += fmt.length;
      msgs_skipped++;
      continue;
    }
    if ( memcmp(fmt.name, "MSG", 3) == 0 )
    {
      // Parse MSG message to extract timestamp and message text.
      // ArduPilot changed the MSG format from "QZ" (TimeUS,Message) to
      // "QBBZ" (TimeUS,ID,Seq,Message), inserting two bytes before the text.
      // Locate the fields by name from the FMT so both layouts parse correctly.
      // (From ArduPilot/plotjuggler-apbin-plugins@3e2f925; PORTING.md #13.)
      APBinMessage log_msg;

      const uint32_t time_offset = get_field_byte_offset(type, "TimeUS");
      const uint32_t text_offset = get_field_byte_offset(type, "Message");
      memcpy(&log_msg.timestamp_us, buf + total_bytes_used + time_offset, sizeof(uint64_t));

      // The Message field spans the remainder of the record. It is only
      // null-terminated if the text is shorter than the field width.
      const char* msg_text = reinterpret_cast<const char*>(buf + total_bytes_used + text_offset);
      const size_t msg_field_size = text_offset < fmt.length ? fmt.length - text_offset : 0;
      log_msg.message.assign(msg_text, strnlen(msg_text, msg_field_size));

      log_messages.push_back(std::move(log_msg));

      total_bytes_used += fmt.length;
      msgs_read++;
      continue;
    }
    if ( memcmp(fmt.name, "PARM", 4) == 0 )
    {
      // Parse PARM message to extract parameter name and value
      // PARM format is typically "QNf" with labels "TimeUS,Name,Value"
      // Q = uint64_t (8 bytes), N = char[16], f = float (4 bytes)
      const uint8_t* msg_ptr = buf + total_bytes_used + LOG_PACKET_HEADER_LEN;

      // Extract TimeUS and convert µs → s (matches the 1e-6 multiplier applied to
      // TimeUS fields in messages_map before apply_timesync runs)
      uint64_t time_us;
      memcpy(&time_us, msg_ptr, sizeof(time_us));
      double timestamp = static_cast<double>(time_us) * 1e-6;
      msg_ptr += sizeof(uint64_t);

      // Extract parameter name (16 bytes max, null-terminated)
      const char* param_name = reinterpret_cast<const char*>(msg_ptr);
      size_t name_len = strnlen(param_name, 16);
      std::string name(param_name, name_len);
      msg_ptr += 16;

      // Extract parameter value (float)
      float value;
      memcpy(&value, msg_ptr, sizeof(value));

      // Keep latest value for dialog
      log_parameters[name] = value;

      // Newer firmware logs "QNff" (TimeUS,Name,Value,Default): keep the default for the
      // Dataset Info entry (ArduPilot/plotjuggler-apbin-plugins@db0618d). Located by name, so
      // older "QNf" logs simply have none.
      const auto& parm_fields = field_name2idx[msg_id2name[type]];
      if (parm_fields.find("Default") != parm_fields.end())
      {
        float default_value;
        memcpy(&default_value, buf + total_bytes_used + get_field_byte_offset(type, "Default"), sizeof(default_value));
        log_parameter_defaults[name] = default_value;
      }

      // Store all entries for time-series plotting
      parm_entries.push_back({timestamp, name, value});

      total_bytes_used += fmt.length;
      msgs_read++;
      continue;
    }

    #ifdef DEBUG_RUNTIME
      auto other_start = std::chrono::high_resolution_clock::now();
    #endif

    if ( !has_fmtu[type] )
    {
      // FMTU hasn't arrived yet for this message type — stash the raw bytes
      // and replay once FMTU lands (or at end-of-file if it never does).
      deferred_messages[type].push_back(&buf[total_bytes_used]);
    }
    else
    {
      handle_message_received(fmt, &buf[total_bytes_used]);
    }

    total_bytes_used += fmt.length;
    msgs_read++; // todo: this is incorrect, if message is read incomplete

    #ifdef DEBUG_RUNTIME
      auto other_end = std::chrono::high_resolution_clock::now();
      other_ms += (other_end - other_start);
    #endif
  }


  // Drain any messages whose FMTU never arrived. They keep instance=""
  // (publish loop skips the suffix because has_instance is false for them).
  for (uint16_t id = 0; id < MAX_FORMATS; ++id)
  {
    auto& deferred = deferred_messages[id];
    if (deferred.empty()) continue;
    const struct log_Format& fmt_for_id = formats[id];
    for (const uint8_t* msg_ptr : deferred)
    {
      handle_message_received(fmt_for_id, msg_ptr);
    }
    deferred.clear();
  }


  // -------------------- process UNITs -------------------- //
  #ifdef DEBUG_RUNTIME
      auto process_units_start = std::chrono::high_resolution_clock::now();
  #endif
  // - convert '/<unit>' spelling because it's incompatible with PlotJuggler
  //    - PlotJuggler uses '/' in names for data splitting into subtopics
  // (PJ4: spelled as UTF-8 bytes; MSVC does not compile this source as UTF-8.)
  const std::string superscript_minus = "\xE2\x81\xBB";  // "⁻"
  const std::array<std::string, 3> superscript_numbers = {"\xC2\xB9", "\xC2\xB2", "\xC2\xB3"};  // "¹", "²", "³"

  for (auto& unit_it : units)
  {
    std::string& unit = unit_it.second;

    std::map<std::string, uint8_t> counter;

    size_t pos = 0;
    while ( (pos = unit.find("/")) != std::string::npos )
    {
      std::string token = unit.substr(pos+1, 1);

      // push to map
      auto counter_it = counter.find(token);
      if (counter_it == counter.end())
      {
        counter[token] = 0;
      }
      else
      {
        counter[token]++;
      }

      // erase old '/<unit>' from string
      // (PORTING.md #22: erases pos+1 characters, not 2; translated as-is.)
      unit.erase(pos, pos + 1);
    }

    // append new style to string
    for (auto& counter_it : counter)
    {
      unit.append(" " + counter_it.first + superscript_minus + superscript_numbers[counter_it.second]);
    }
  }
  #ifdef DEBUG_RUNTIME
    auto process_units_end = std::chrono::high_resolution_clock::now();
    process_units_ms += (process_units_end - process_units_start);
  #endif


  // -------------------- apply multipliers -------------------- //
  #ifdef DEBUG_RUNTIME
    auto apply_mult_start = std::chrono::high_resolution_clock::now();
  #endif
  apply_multipliers();
  #ifdef DEBUG_RUNTIME
    auto apply_mult_end = std::chrono::high_resolution_clock::now();
    apply_mult_ms += (apply_mult_end - apply_mult_start);
  #endif


  // -------------------- apply timesync -------------------- //
  #ifdef DEBUG_RUNTIME
    auto apply_tsync_start = std::chrono::high_resolution_clock::now();
  #endif
  apply_timesync();
  #ifdef DEBUG_RUNTIME
    auto apply_tsync_end = std::chrono::high_resolution_clock::now();
    apply_tsync_ms += (apply_tsync_end - apply_tsync_start);
  #endif



  #ifdef DEBUG_MESSAGES
  std::printf("\n--------- DEBUG_MESSAGES ---------");
  for (int idx=0; idx < 256; idx++)
  {
    if (has_fmt[idx])
    {
      const struct log_Format& fmt = formats[idx];
      std::string msg_name = std::string(fmt.name, MAX_NAME_SIZE);
      std::string msg_labels = std::string(fmt.labels, MAX_LABELS_SIZE);
      std::string msg_format = std::string(fmt.format, MAX_FORMAT_SIZE);
      std::printf("\n%s:\n", msg_name.c_str());
      std::printf("  -id: \t\t%u\n", fmt.type);
      std::printf("  -labels: \t%s\n", msg_labels.c_str());
      std::printf("  -format: \t%s\n", msg_format.c_str());
      if (has_fmtu[idx])
      {
        const struct log_Format_Units& fmtu = format_units[idx];
        std::string msg_units = std::string(fmtu.units, MAX_UNITS_SIZE);
        std::string msg_multipliers = std::string(fmtu.multipliers, MAX_MULTIPLIERS_SIZE);
        std::printf("  -units: \t%s\n", msg_units.c_str());
        std::printf("  -multipliers: %s\n", msg_multipliers.c_str());
        if (has_instance[idx] == true)
        {
          std::printf("  -has instance at idx: %i\n", instance_idx[idx]);
        }
      }
    }
  }
  std::printf("-------------- END --------------\n\n");
  #endif

  #ifdef DEBUG_MULTIPLIERS
  std::printf("\n------- DEBUG_MULTIPLIERS -------\n");
  for(const auto& multi_it : multipliers)
  {
    std::cout << multi_it.first << ": " << multi_it.second << std::endl;
  }
  std::printf("-------------- END --------------\n\n");
  #endif

  #ifdef DEBUG_UNITS
  std::printf("\n---------- DEBUG_UNITS ----------\n");
  for(const auto& unit_it : units)
  {
    std::cout << unit_it.first << ": " << unit_it.second << std::endl;
  }
  std::printf("-------------- END --------------\n\n");
  #endif



  // -------------------- publish to plotjuggler -------------------- //
  #ifdef DEBUG_RUNTIME
    auto publish_start = std::chrono::high_resolution_clock::now();
  #endif
  if (auto status = publish(); !status)
  {
    return status;
  }
  #ifdef DEBUG_RUNTIME
    auto publish_end = std::chrono::high_resolution_clock::now();
    publish_ms += (publish_end - publish_start);
  #endif

  #ifdef DEBUG_RUNTIME
    std::chrono::duration<double, std::milli> total_ms = fmt_ms + fmtu_ms + mult_ms + unit_ms + other_ms + process_units_ms + apply_mult_ms + apply_tsync_ms + publish_ms;
    std::printf("\n--------- DEBUG_RUNTIME ---------");
    std::printf("\nFMT-Loading (ms): \t%.2f", fmt_ms.count());
    std::printf("\nFMTU-Loading (ms): \t%.2f", fmtu_ms.count());
    std::printf("\nMULT-Loading (ms): \t%.2f", mult_ms.count());
    std::printf("\nUNIT-Loading (ms): \t%.2f", unit_ms.count());
    std::printf("\nOTHER-Loading (ms): \t%.2f\n", other_ms.count());

    std::printf("\nProcess-Units (ms):\t%.2f", process_units_ms.count());
    std::printf("\nApply-Multipliers (ms):\t%.2f", apply_mult_ms.count());
    std::printf("\nApply-Timesync (ms):\t%.2f", apply_tsync_ms.count());
    std::printf("\nPublish (ms):\t\t%.2f", publish_ms.count());
    std::printf("\n---------------------------------");
    std::printf("\nTOTAL (ms):\t\t%.2f", total_ms.count());
    std::printf("\n-------------- END --------------\n\n");
  #endif

  const auto elapsed_ms =
      std::chrono::duration_cast<std::chrono::milliseconds>(std::chrono::steady_clock::now() - timer_start).count();
  std::printf("The loading operation took %lld milliseconds\n", static_cast<long long>(elapsed_ms));

  std::printf("\n  Read messages:\t%d", msgs_read);
  std::printf("\n  Skipped messages:\t%d", msgs_skipped);
  std::printf("\n  Skipped bytes:\t%d from %d bytes\n\n", bytes_skipped, len);

  // PJ4: the same statistics in the host's message log (PJ3 printed them to stdout only).
  runtimeHost().reportMessage(
      PJ::DataSourceMessageLevel::kInfo,
      "ArduPilot Bin: read " + std::to_string(msgs_read) + " messages, skipped " + std::to_string(msgs_skipped) +
          " messages and " + std::to_string(bytes_skipped) + " of " + std::to_string(len) + " bytes in " +
          std::to_string(elapsed_ms) + " ms");

  return PJ::okStatus();
}


PJ::Status APBinSource::publish()
{
  // iterate through messages
  for (const auto& msg_it : messages_map)
  {
    const std::string& msg_name = msg_it.first;

    // get message id for message name
    const uint8_t& msg_id = msg_name2id[msg_name];

    // only publish messages to plotjuggler, which have the "TimeUS" field!
    auto time_idx_it = field_name2idx[msg_name].find("TimeUS");
    if (time_idx_it == field_name2idx[msg_name].end())
    {
      std::printf("Ignoring message '%s' because it has no 'TimeUS' field!\n", msg_name.c_str());
      continue;
    }

    const std::vector<bool>& scaled = scaled_fields[msg_name];

    // iterate through instances
    const auto& instances_map = msg_it.second;
    for (const auto& inst_it : instances_map)
    {
      const message_data& msg_data = inst_it.second;

      // extract timestamps from message data
      const uint8_t& time_idx = field_name2idx[msg_name]["TimeUS"];
      const std::vector<double>& timestamps = msg_data[time_idx].second;

      // PJ3: series "/<MSG>/<field>" or "/<MSG>/#<instance>/<field>".
      // PJ4: topic "<MSG>" or "<MSG>/#<instance>", one field per column (PORTING.md, decision 2).
      const std::string instance_name = "#" + inst_it.first;
      const std::string topic_name = !has_instance[msg_id] ? msg_name : msg_name + "/" + instance_name;

      auto topic = writeHost().ensureTopic(topic_name);
      if (!topic)
      {
        return PJ::unexpected(topic.error());
      }

      // iterate through fields
      struct PublishedField { size_t idx; PJ::sdk::FieldHandle handle; PJ::PrimitiveType type; };
      std::vector<PublishedField> fields;

      size_t idx = 0;
      for (const auto& field : msg_data)
      {
        if ( idx == time_idx || ( has_instance[msg_id] && (static_cast<int>(idx) == instance_idx[msg_id]) ) )
        {
          idx++;
          continue;
        }

        std::string field_name = field.first;

        #ifdef LABEL_WITH_UNIT
          std::string unit_str = get_unit(msg_name, field_name);
          if ( !unit_str.empty() )
          {
            field_name = field_name + "\t[" + unit_str + "]";
          }
        #endif

        const bool is_scaled = idx < scaled.size() && scaled[idx];
        const PJ::PrimitiveType type =
            is_scaled ? PJ::PrimitiveType::kFloat64 : primitive_type_for(formats[msg_id].format[idx]);

        auto handle = writeHost().ensureField(*topic, field_name, type);
        if (!handle)
        {
          return PJ::unexpected(handle.error());
        }
        fields.push_back({idx, *handle, type});
        idx++;
      }

      // PJ4: rows instead of per-series points. A field shorter than the timestamps (a record
      // whose decoding stopped at an unknown format type) is left null in the remaining rows.
      std::vector<PJ::sdk::BoundFieldValue> row;
      row.reserve(fields.size());
      for (size_t i = 0; i < timestamps.size(); i++)
      {
        row.clear();
        for (const auto& f : fields)
        {
          const std::vector<double>& values = msg_data[f.idx].second;
          if (i < values.size())
          {
            row.push_back({.field = f.handle, .value = value_ref_for(f.type, values[i])});
          }
        }
        auto status = writeHost().appendBoundRecord(
            *topic, to_timestamp(timestamps[i]), PJ::Span<const PJ::sdk::BoundFieldValue>(row.data(), row.size()));
        if (!status)
        {
          return status;
        }
      }
    }
  }

  // Publish PARM entries as time series: /PARM/<name>
  for (const auto& entry : parm_entries)
  {
    auto topic = writeHost().ensureTopic("_PARM/" + entry.name);
    if (!topic)
    {
      return PJ::unexpected(topic.error());
    }
    auto status = writeHost().appendRecord(
        *topic, to_timestamp(entry.timestamp), {{.name = "value", .value = static_cast<double>(entry.value)}});
    if (!status)
    {
      return status;
    }
  }

  // PJ4 (decision 1): MSG text as a time-synced text topic. PJ3 only showed it in the info dialog.
  if (!log_messages.empty())
  {
    auto topic = writeHost().ensureTopic("_MSG");
    if (!topic)
    {
      return PJ::unexpected(topic.error());
    }
    for (const auto& msg : log_messages)
    {
      const double timestamp = static_cast<double>(msg.timestamp_us) * 1e-6 + time_offset_s;
      auto status = writeHost().appendRecord(
          *topic, to_timestamp(timestamp), {{.name = "message", .value = std::string_view(msg.message)}});
      if (!status)
      {
        return status;
      }
    }
  }

  if (auto status = publish_vehicle_transforms(); !status)
  {
    return status;
  }

  // PJ3: show the log info dialog (Parameters / Message Logs) if there are any messages or
  // parameters. PJ4 (decision 1): the same content goes into the dataset metadata, shown in the
  // host's Dataset Info window.
  if (!log_messages.empty() || !log_parameters.empty())
  {
    // Parameters: latest value per name, sorted by name (std::map, as sortItems(0) did).
    // Values are rendered like QString::number(float): 6 significant digits, %g style. Qt rounds
    // an exact tie half away from zero (34259.25 -> "34259.3") where printf rounds half to even
    // ("34259.2"). A float widened to double only sits exactly on a 6-digit rounding boundary
    // when it is such a tie, so stepping one double ulp away from zero reproduces Qt's result
    // for ties and changes nothing else. Zero is never a tie and must not be stepped (it would
    // become the smallest subnormal).
    const auto format_value = [](float v) {
      const double widened = static_cast<double>(v);
      const double qt_rounded =
          widened == 0.0 ? widened
                         : std::nextafter(widened, widened < 0 ? -std::numeric_limits<double>::infinity()
                                                               : std::numeric_limits<double>::infinity());
      char text[32];
      std::snprintf(text, sizeof(text), "%g", qt_rounded);
      return std::string(text);
    };

    // Newer firmware also logs each parameter's default: shown after the value.
    nlohmann::json parameters = nlohmann::json::object();
    for (const auto& param : log_parameters)
    {
      std::string value = format_value(param.second);
      if (const auto it = log_parameter_defaults.find(param.first); it != log_parameter_defaults.end())
      {
        value += "  (default " + format_value(it->second) + ")";
      }
      parameters[param.first] = value;
    }

    // Message Logs: timestamp in seconds since boot with 2 decimals (not time-synced, as in PJ3).
    nlohmann::json messages = nlohmann::json::array();
    for (const auto& msg : log_messages)
    {
      char time[32];
      std::snprintf(time, sizeof(time), "%.2f", msg.timestamp_us / 1000000.0);
      messages.push_back(std::string(time) + " s  " + msg.message);
    }

    nlohmann::json metadata = nlohmann::json::object();
    metadata["Parameters"] = std::move(parameters);
    metadata["Message Logs"] = std::move(messages);

    // Older hosts without the metadata slot return an error; the load proceeds without it.
    (void)runtimeHost().setDatasetMetadata(metadata.dump(-1, ' ', false, nlohmann::json::error_handler_t::replace));
  }

  return PJ::okStatus();
}


PJ::Status APBinSource::publish_vehicle_transforms()
{
  // PJ4: new in the port (not in PJ3). XKF1, one instance per EKF3 core, carries the local
  // position (metres north/east/down from the EKF origin) and the attitude together. The pose
  // follows the primary core over time, as reported by XKF4's PI field (core 0 if not logged).
  const char* const kFields[] = {"TimeUS", "PN", "PE", "PD", "Roll", "Pitch", "Yaw"};
  constexpr size_t kFieldCount = std::size(kFields);

  const auto xkf1_it = messages_map.find("XKF1");
  if (xkf1_it == messages_map.end() || xkf1_it->second.empty())
  {
    return PJ::okStatus();  // no EKF3 output in this log: no 3D pose
  }

  // Field positions and units, identical for every core.
  const auto& name2idx = field_name2idx["XKF1"];
  const uint8_t msg_id = msg_name2id["XKF1"];
  const std::vector<bool>& scaled = scaled_fields["XKF1"];
  uint8_t field_idx[kFieldCount] = {};
  double factors[kFieldCount] = {};
  for (size_t i = 0; i < kFieldCount; i++)
  {
    const auto idx_it = name2idx.find(kFields[i]);
    if (idx_it == name2idx.end())
    {
      runtimeHost().reportMessage(PJ::DataSourceMessageLevel::kWarning,
                                  std::string("ArduPilot Bin: XKF1 has no '") + kFields[i] +
                                      "' field, the 3D vehicle pose is not available");
      return PJ::okStatus();
    }
    const uint8_t idx = idx_it->second;
    field_idx[i] = idx;
    // Without FMTU no multiplier was applied: the centi-unit formats are still x100.
    const char format_char = formats[msg_id].format[idx];
    const bool centi = format_char == 'c' || format_char == 'C' || format_char == 'e' || format_char == 'E';
    factors[i] = (i > 0 && centi && !(idx < scaled.size() && scaled[idx])) ? 0.01 : 1.0;
  }

  // Primary core over time: XKF4.PI. Every core's XKF4 logs it; use core 0's (else the first).
  std::vector<double> primary_times;
  std::vector<double> primary_cores;
  if (const auto xkf4_it = messages_map.find("XKF4"); xkf4_it != messages_map.end() && !xkf4_it->second.empty())
  {
    const auto inst_it = xkf4_it->second.find("0");
    const message_data& xkf4 = inst_it != xkf4_it->second.end() ? inst_it->second : xkf4_it->second.begin()->second;
    const auto& xkf4_idx = field_name2idx["XKF4"];
    const auto time_it = xkf4_idx.find("TimeUS");
    const auto pi_it = xkf4_idx.find("PI");
    if (time_it != xkf4_idx.end() && pi_it != xkf4_idx.end() && time_it->second < xkf4.size() &&
        pi_it->second < xkf4.size())
    {
      primary_times = xkf4[time_it->second].second;
      primary_cores = xkf4[pi_it->second].second;
      const size_t n = std::min(primary_times.size(), primary_cores.size());
      primary_times.resize(n);
      primary_cores.resize(n);
    }
  }
  if (primary_times.empty())
  {
    runtimeHost().reportMessage(PJ::DataSourceMessageLevel::kInfo,
                                "ArduPilot Bin: no XKF4 primary-core index (PI) in this log, the 3D vehicle pose "
                                "uses EKF core 0");
  }
  // The core that was primary at time t: the last PI logged at or before t (the first PI before
  // the first XKF4 sample).
  const auto primary_at = [&](double t) {
    if (primary_times.empty())
    {
      return 0L;
    }
    const auto it = std::upper_bound(primary_times.begin(), primary_times.end(), t);
    const size_t k = it == primary_times.begin() ? 0 : static_cast<size_t>(it - primary_times.begin()) - 1;
    return std::lround(primary_cores[k]);
  };

  // XKF1 samples of whichever core was primary at their time, merged in time order.
  struct PoseSample
  {
    double time;
    const message_data* data;
    size_t row;
  };
  std::vector<PoseSample> samples;
  for (const auto& [instance, data] : xkf1_it->second)
  {
    long core = 0;
    if (has_instance[msg_id])
    {
      char* end = nullptr;
      core = std::strtol(instance.c_str(), &end, 10);
      if (end == instance.c_str() || *end != '\0')
      {
        continue;  // not a numeric core index
      }
    }
    size_t count = std::numeric_limits<size_t>::max();
    for (const uint8_t idx : field_idx)
    {
      count = idx < data.size() ? std::min(count, data[idx].second.size()) : 0;
    }
    if (count == 0)
    {
      continue;
    }
    const std::vector<double>& times = data[field_idx[0]].second;
    for (size_t row = 0; row < count; row++)
    {
      if (primary_at(times[row]) == core)
      {
        samples.push_back({times[row], &data, row});
      }
    }
  }
  std::stable_sort(samples.begin(), samples.end(),
                   [](const PoseSample& a, const PoseSample& b) { return a.time < b.time; });

  const auto* object_host = objectWriteHost();
  if (object_host == nullptr)
  {
    return PJ::okStatus();  // host without an object store: numeric data only
  }
  auto topic = object_host->registerTopic("_TF", PJ::sdk::BuiltinObjectType::kFrameTransforms);
  if (!topic)
  {
    return PJ::unexpected(topic.error());
  }

  PJ::sdk::FrameTransforms message;
  message.transforms.resize(1);
  PJ::sdk::FrameTransform& tf = message.transforms.front();
  tf.parent_frame_id = "world";
  tf.child_frame_id = "vehicle";
  for (const PoseSample& sample : samples)
  {
    const auto value = [&](size_t field) { return (*sample.data)[field_idx[field]].second[sample.row] * factors[field]; };
    const double north = value(1), east = value(2), down = value(3);
    const double roll = value(4), pitch = value(5), yaw = value(6);
    if (!std::isfinite(north) || !std::isfinite(east) || !std::isfinite(down) || !std::isfinite(roll) ||
        !std::isfinite(pitch) || !std::isfinite(yaw))
    {
      continue;
    }
    tf.timestamp = to_timestamp(sample.time);
    tf.translation = {.x = east, .y = north, .z = -down};
    tf.rotation = enu_flu_quaternion(roll, pitch, yaw);
    const std::vector<uint8_t> bytes = PJ::serializeFrameTransforms(message);
    if (auto status = object_host->pushOwned(*topic, tf.timestamp, PJ::Span<const uint8_t>(bytes.data(), bytes.size()));
        !status)
    {
      return status;
    }
  }
  return PJ::okStatus();
}


void APBinSource::handle_message_received(const struct log_Format& fmt, const uint8_t* msg)
{
  // message id
  const uint8_t& msg_id = fmt.type;

  // message name
  const std::string& msg_name = msg_id2name[msg_id];

  // instances
  std::string instance;
  if ( has_instance[msg_id] )
  {
    instance = get_instance(fmt, msg);
  }

  // check if message already exists in messages_map
  auto message_it = messages_map.find(msg_name);
  if (message_it == messages_map.end())
  {
    messages_map[msg_name];
  }

  // check if instance already exists in message_map[msg_name]
  auto instance_it = messages_map[msg_name].find(instance);
  if (instance_it == messages_map[msg_name].end())
  {
    messages_map[msg_name][instance] = create_message_data(fmt);
  }
  message_data& msg_data = messages_map[msg_name][instance];

  uint32_t msg_offset = LOG_PACKET_HEADER_LEN;  // discard header


  /*
    If you need to change this section, please also fix logformat.h (format_types)!
    AP_Logger: Format Types (https://github.com/ArduPilot/ardupilot/tree/master/libraries/AP_Logger#format-types)
      - file: libraries/AP_Logger/LogStructure.h (commit: b80cc9a)
      - line: 9 - 28
  */

  // for each field, we get the data according to the format types
  // this uses pointer arithmetic, so just close your eyes
  // (PJ4: memcpy instead of dereferencing unaligned pointers; same values.)
  auto read = [&](auto tag) {
    decltype(tag) v;
    memcpy(&v, msg + msg_offset, sizeof(v));
    msg_offset += sizeof(v);
    return static_cast<double>(v);
  };

  double value{ 0 };
  for (size_t i = 0; i < msg_data.size(); i++)
  {
    const char typeCode = fmt.format[i];
    switch (typeCode)
    {
      case 'a':
        // not used, that is for ISBD
        msg_offset += sizeof(int16_t[32]);
        break;
      case 'b': value = read(int8_t{}); break;
      case 'B': value = read(uint8_t{}); break;
      case 'h': value = read(int16_t{}); break;
      case 'H': value = read(uint16_t{}); break;
      case 'i': value = read(int32_t{}); break;
      case 'I': value = read(uint32_t{}); break;
      case 'f': value = read(float{}); break;
      case 'd': value = read(double{}); break;
      case 'n':
        // not used, that is for MSG or PARAM
        msg_offset += sizeof(char[4]);
        break;
      case 'N':
        // not used, that is for MSG or PARAM
        msg_offset += sizeof(char[16]);
        break;
      case 'Z':
        // not used, that is for MSG or PARAM
        msg_offset += sizeof(char[64]);
        break;
      case 'c': value = read(int16_t{}); break;
      case 'C': value = read(uint16_t{}); break;
      case 'e': value = read(int32_t{}); break;
      case 'E': value = read(uint32_t{}); break;
      case 'L': value = read(int32_t{}); break;
      case 'M': value = read(uint8_t{}); break;
      case 'q': value = read(int64_t{}); break;
      case 'Q': value = read(uint64_t{}); break;
      default:
        std::fprintf(stderr, "ERROR: format type '%c' is not defined!\n", typeCode);
        // At this point the field offset is unknown, therefore we can not proceed to interpret the remaining fields!
        return;
    }

    // (PORTING.md #15: for 'a'/'n'/'N'/'Z' this pushes the previous field's value; translated as-is.)
    msg_data[i].second.push_back(value);

  }
}



APBinSource::message_data APBinSource::create_message_data(const struct log_Format& fmt)
{
  // PJ3: QString(fmt.labels).truncate(MAX_LABELS_SIZE).split(",") (empty parts kept)
  std::string labelStr(fmt.labels, strnlen(fmt.labels, MAX_LABELS_SIZE));
  std::vector<std::string> labels_list;
  if (labelStr.size() > 0)
  {
    size_t start = 0;
    size_t pos;
    while ((pos = labelStr.find(',', start)) != std::string::npos)
    {
      labels_list.push_back(labelStr.substr(start, pos - start));
      start = pos + 1;
    }
    labels_list.push_back(labelStr.substr(start));
  }

  message_data msg_data;
  msg_data.reserve(labels_list.size());
  for (size_t i = 0; i < labels_list.size(); i++)
  {
    msg_data.emplace_back(labels_list.at(i), std::vector<double>());
  }
  return msg_data;
}



uint32_t APBinSource::get_field_byte_offset(const uint8_t& msg_id, const uint8_t& field_idx)
{
  // check if FMT exists
  if ( !has_fmt[msg_id])
  {
    // raise error, because fmt does not exist!
    // PJ4: PJ3 printed this and called exit(EXIT_FAILURE); see FatalLogError.
    char message[64];
    std::snprintf(message, sizeof(message), "FMT for message %u does not exist!", msg_id);
    std::fprintf(stderr, "ERROR: %s\n", message);
    throw FatalLogError(message);
  }

  // get information from FMT
  const struct log_Format& fmt = formats[msg_id];
  const char* format = fmt.format;

  // calculate offsets:

  // - header offset
  uint32_t header_offset = LOG_PACKET_HEADER_LEN;

  // - data offset
  uint32_t data_offset = 0;
  for (uint8_t idx = 0; idx < field_idx; idx++)
  {
    const auto format_types_it = format_types.find(format[idx]);
    if ( format_types_it == format_types.end() )
    {
      // raise error, because format type definition is missing
      char message[64];
      std::snprintf(message, sizeof(message), "format type '%c' is not defined!", format[idx]);
      std::fprintf(stderr, "ERROR: %s\n", message);
      throw FatalLogError(message);
    }
    data_offset += format_types_it->second;
  }

  uint32_t total_offset = header_offset + data_offset;

  return total_offset;
}



uint32_t APBinSource::get_field_byte_offset(const uint8_t& msg_id, const std::string& field_name)
{
  const std::string& msg_name = msg_id2name[msg_id];
  const uint8_t field_idx = field_name2idx[msg_name][field_name];

  return get_field_byte_offset(msg_id, field_idx);
}



std::string APBinSource::get_instance(const struct log_Format& fmt, const uint8_t* msg)
{
  // Decode the instance identifier from the raw message bytes according to
  // the FMT type of the field flagged with '#' in FMTU.units. For string
  // fields (N=char[16], n=char[4], Z=char[64]) the full null-terminated
  // string is used — otherwise the script Name byte for SCR would collapse
  // every script sharing a first character into the same instance bucket.

  const uint8_t& msg_id = fmt.type;
  const uint32_t inst_offset = instance_offset[msg_id];
  const int inst_idx = instance_idx[msg_id];
  const char inst_fmt = fmt.format[inst_idx];

  auto read = [&](auto tag) {
    decltype(tag) v;
    memcpy(&v, &msg[inst_offset], sizeof(v));
    return std::to_string(v);
  };

  switch (inst_fmt)
  {
    case 'N':  // char[16]
    {
      char buf[17] = {0};
      memcpy(buf, &msg[inst_offset], 16);
      return std::string(buf);
    }
    case 'n':  // char[4]
    {
      char buf[5] = {0};
      memcpy(buf, &msg[inst_offset], 4);
      return std::string(buf);
    }
    case 'Z':  // char[64]
    {
      char buf[65] = {0};
      memcpy(buf, &msg[inst_offset], 64);
      return std::string(buf);
    }
    case 'b': return read(int8_t{});
    case 'B': return read(uint8_t{});
    case 'h': return read(int16_t{});
    case 'H': return read(uint16_t{});
    case 'i': return read(int32_t{});
    case 'I': return read(uint32_t{});
    case 'f': return read(float{});
    case 'd': return read(double{});
    case 'c': return read(int16_t{});
    case 'C': return read(uint16_t{});
    case 'e': return read(int32_t{});
    case 'E': return read(uint32_t{});
    case 'L': return read(int32_t{});
    case 'M': return read(uint8_t{});
    case 'q': return read(int64_t{});
    case 'Q': return read(uint64_t{});
    default:
      // Unknown type at the '#' position: fall back to a single-byte read so
      // we preserve previous behavior rather than crashing on a malformed log.
      return std::to_string(static_cast<int>(msg[inst_offset]));
  }
}



std::string APBinSource::get_unit(const std::string& msg_name, const std::string& field_name)
{
  // get message id for message name
  const uint8_t& msg_id = msg_name2id[msg_name];

  // check if FMTU exists
  if ( !has_fmtu[msg_id] )
  {
    std::fprintf(stderr, "\nWARNING: no FMTU for message %s found! Can not apply units!\n", msg_name.c_str());
    return "";
  }

  // get data index of field
  const uint8_t& idx = field_name2idx[msg_name][field_name];

  // get unit descriptor char
  const char& unit_char = format_units[msg_id].units[idx];

  // get unit string
  const auto& unit_it = units.find(unit_char);
  if ( unit_it == units.end() )
  {
    std::fprintf(stderr, "WARNING: No unit for unit-id %c found! Can not apply unit in message: %s\n", unit_char, msg_name.c_str());
    return "";
  }

  return unit_it->second;
}



void APBinSource::apply_multipliers(void)
{
  // Go through all messages, instances, fields and apply the correct multiplier from FMTU and MULT

  // iterate through messages
  for (auto& msg_it : messages_map)
  {
    const std::string& msg_name = msg_it.first;

    // get message id for message name
    const uint8_t& msg_id = msg_name2id[msg_name];

    // check if FMTU exists
    if ( !has_fmtu[msg_id] )
    {
      std::fprintf(stderr, "WARNING: No FMTU for message %s found. Can not apply multipliers!\n", msg_name.c_str());
      continue;
    }

    // iterate through instances
    auto& instances_map = msg_it.second;
    for (auto& inst_it : instances_map)
    {
      message_data& msg_data = inst_it.second;

      // PJ4: remember which fields get scaled (identical for every instance of a message).
      std::vector<bool>& scaled = scaled_fields[msg_name];
      scaled.resize(std::max(scaled.size(), msg_data.size()), false);

      // iterate through fields
      for (size_t idx = 0; idx < msg_data.size(); idx++)
      {
        // get multiplier descriptor char
        const char& field_multiplier_char = format_units[msg_id].multipliers[idx];

        // get multiplier double
        const auto multiplier_it = multipliers.find(field_multiplier_char);
        if ( multiplier_it == multipliers.end() )
        {
          std::fprintf(stderr, "WARNING: No multiplier for multiplier-id %c found! Can not apply multiplier in message: %s\n", field_multiplier_char, msg_name.c_str());
          continue;
        }
        const double field_multiplier = multiplier_it->second;

        // check if multiplier is 0 or 1
        if ( is_nearly(field_multiplier, 0) || is_nearly(field_multiplier, 1) )
        {
          continue;
        }

        std::vector<double>& field_data = msg_data[idx].second;
        std::transform(field_data.begin(), field_data.end(), field_data.begin(), std::bind(std::multiplies<double>(), std::placeholders::_1, field_multiplier));
        scaled[idx] = true;
      }
    }
  }
}



void APBinSource::apply_timesync(void)
{
  // ArduPilot logs should be comparable with rosbags, therefore the same time basis is needed...
  //  - rosbag:         unix time
  //  - ArduPilot log:  local time since power on
  //    -> the logged GNSS time can be used for synchronisation

  // extract GNSS time
  const auto msg_it = messages_map.find("GPS");
  if ( msg_it == messages_map.end() )
  {
    std::printf("Skipping timesync because the logfile does not contain GNSS data\n");
    return;
  }

  // take the first instance as reference
  // todo: change that?
  if ( msg_it->second.empty() )
  {
    std::printf("Skipping timesync because GPS message has no instances\n");
    return;
  }
  const message_data& gps_msg_data = msg_it->second.begin()->second;

  // get needed field indexes, by name: a missing field skips the sync instead of silently
  // reading field 0 (ArduPilot/plotjuggler-apbin-plugins@49208c1; PORTING.md #18b)
  const auto& gps_fields = field_name2idx["GPS"];
  std::array<uint8_t, 4> idx{};  // TimeUS, GWk (GPS week), GMS (GPS ms in week), NSats
  const std::array<const char*, 4> labels = {"TimeUS", "GWk", "GMS", "NSats"};
  for (size_t i = 0; i < labels.size(); i++)
  {
    const auto it = gps_fields.find(labels[i]);
    if (it == gps_fields.end() || it->second >= gps_msg_data.size())
    {
      std::printf("Skipping timesync because GPS message has no '%s' field!\n", labels[i]);
      return;
    }
    idx[i] = it->second;
  }
  const std::vector<double>& time_vec = gps_msg_data[idx[0]].second;
  const std::vector<double>& week_vec = gps_msg_data[idx[1]].second;
  const std::vector<double>& ms_vec = gps_msg_data[idx[2]].second;
  const std::vector<double>& nsats_vec = gps_msg_data[idx[3]].second;

  // Anchor on the first sample with a usable fix: enough satellites and non-zero
  // TimeUS/GWk/GMS. GWk must be checked: a sample can report satellites while the week number
  // is still unresolved (0), which would anchor the whole log to the GPS epoch (1980-01-06).
  // (ArduPilot/plotjuggler-apbin-plugins@39d5c7f, @49208c1; PORTING.md #18a. PJ3 used sample [1].)
  static constexpr double MIN_VALID_NSATS = 4;
  size_t anchor = time_vec.size();
  for (size_t i = 0; i < time_vec.size(); i++)
  {
    if (i < week_vec.size() && i < ms_vec.size() && i < nsats_vec.size() && nsats_vec[i] >= MIN_VALID_NSATS &&
        time_vec[i] != 0.0 && week_vec[i] > 0.0 && ms_vec[i] > 0.0)
    {
      anchor = i;
      break;
    }
  }
  if (anchor == time_vec.size())
  {
    std::printf("Skipping timesync because no GPS sample with a valid fix was found\n");
    return;
  }

  // constant time offset variables
  static constexpr double GPS2UNIX_TIME_OFFSET = 315964800;   // time offset between unix and gps time
  static constexpr double GPS2UNIX_LEAP_SECONDS = -18;        // additional time offset due to leap seconds (must be adjusted if number of leap seconds changes!)
  static constexpr double SECONDS_PER_WEEK = 604800;          // number of seconds per week

  const double& gps_week = week_vec[anchor];

  // GMS is logged in milliseconds. When FMTU gives it a multiplier (modern logs: 'C', 0.001),
  // apply_multipliers() has already scaled it, and PJ3 multiplied by 0.001 a second time,
  // shifting every absolute timestamp by GMS * 0.999 (up to 7 days; PORTING.md, upstream
  // review). Undo the applied multiplier to recover the exact integer milliseconds instead: the
  // multiplier is stored at float precision (0.0010000000475), which would otherwise move the
  // anchor by ~20 ms.
  double gps_week_ms = ms_vec[anchor];
  const auto scaled_it = scaled_fields.find("GPS");
  if (scaled_it != scaled_fields.end() && idx[2] < scaled_it->second.size() && scaled_it->second[idx[2]])
  {
    const char multiplier_char = format_units[msg_name2id["GPS"]].multipliers[idx[2]];
    gps_week_ms = std::round(gps_week_ms / multipliers[multiplier_char]);
  }
  const double gps_week_seconds = gps_week_ms * 0.001;

  const double unix_time = gps_week * SECONDS_PER_WEEK + gps_week_seconds + GPS2UNIX_TIME_OFFSET + GPS2UNIX_LEAP_SECONDS;

  const double& log_time = time_vec[anchor];

  const double time_offset = unix_time - log_time;
  time_offset_s = time_offset;


  // iterate through messages
  for (auto& msg_it : messages_map)
  {
    const auto& msg_name = msg_it.first;

    auto time_idx_it = field_name2idx[msg_name].find("TimeUS");
    if (time_idx_it == field_name2idx[msg_name].end())
    {
      continue;
    }
    auto& time_idx = time_idx_it->second;

    // iterate through instances
    auto& instances_map = msg_it.second;
    for (auto& inst_it : instances_map)
    {
      // add time offset
      message_data& msg_data = inst_it.second;

      std::vector<double>& timestamps = msg_data[time_idx].second;
      std::transform(timestamps.begin(), timestamps.end(), timestamps.begin(), std::bind(std::plus<double>(), std::placeholders::_1, time_offset));
    }
  }

  for (auto& entry : parm_entries)
  {
    entry.timestamp += time_offset;
  }
}

